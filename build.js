/**
 * build.js - Bundles modular scripts into js/bundle.js
 */

const fs = require('fs');
const path = require('path');

const JS_DIR = path.join(__dirname, 'js');
const MODULE_FILES = [
  'storage.js',
  'calendar.js',
  'statistics.js',
  'charts.js',
  'app.js'
];

console.log('Building js/bundle.js from modular sources...');

const cleanedModules = MODULE_FILES.map(fileName => {
  const filePath = path.join(JS_DIR, fileName);
  let content = fs.readFileSync(filePath, 'utf8');

  // Strip BOM if present and persist clean file
  if (content.charCodeAt(0) === 0xFEFF) {
    content = content.slice(1);
    fs.writeFileSync(filePath, content, 'utf8');
  }

  // Strip import statements and export keywords
  const processed = content
    .replace(/^\s*import\s+.*?;?\r?\n/gm, '')
    .replace(/^\s*export\s+(const|class|function|let|var)\s+/gm, '$1 ')
    .trim();

  return `// --- ${fileName} ---\n${processed}`;
});

const banner = `/**
 * Standalone Bundled Script for Habit Tracker Dashboard
 * Auto-generated by build.js - Supports file:// and http:// execution
 */
(function() {
'use strict';
`;

const footer = `
})();
`;

const bundleContent = banner + '\n' + cleanedModules.join('\n\n') + '\n' + footer;
fs.writeFileSync(path.join(JS_DIR, 'bundle.js'), bundleContent, 'utf8');

console.log(`Successfully built js/bundle.js (${bundleContent.length} bytes)`);
